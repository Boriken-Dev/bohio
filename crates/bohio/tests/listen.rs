// Generated bytes.

/// Bytes sent each way in a matrix case.
const LEN: usize = 3 * 1024 * 1024;

/// `len` bytes of a stream that depends only on `seed`, in chunks of varying size, to `sink`.
fn generate(
    seed: u64,
    len: usize,
    mut sink: impl FnMut(&[u8]) -> io::Result<()>,
) -> io::Result<()> {
    let mut state = seed | 1;
    let mut sent = 0;
    let mut chunk = 0_usize;
    while sent < len {
        chunk += 1;
        let size = (1000 + (chunk % 9) * 1500).min(len - sent);
        let bytes: Vec<u8> = (0..size)
            .map(|_| {
                state ^= state << 13;
                state ^= state >> 7;
                state ^= state << 17;
                state.to_le_bytes()[3]
            })
            .collect();
        sink(&bytes)?;
        sent += size;
    }
    Ok(())
}

fn digest_of(seed: u64, len: usize) -> Vec<u8> {
    let mut hasher = Sha256::new();
    generate(seed, len, |bytes| {
        hasher.update(bytes);
        Ok(())
    })
    .expect("hashing cannot fail");
    hasher.finalize().to_vec()
}

// Connections of any kind.

/// A reader that retries the timeouts a socket or pipe read reports, until nothing has come for a while.
struct Patient(Box<dyn Read + Send>);

impl Read for Patient {
    fn read(&mut self, buffer: &mut [u8]) -> io::Result<usize> {
        let start = Instant::now();
        loop {
            match self.0.read(buffer) {
                Err(error)
                    if matches!(
                        error.kind(),
                        io::ErrorKind::TimedOut
                            | io::ErrorKind::WouldBlock
                            | io::ErrorKind::Interrupted
                    ) =>
                {
                    if start.elapsed() > WAIT {
                        return Err(io::Error::new(io::ErrorKind::TimedOut, "nothing came"));
                    }
                }
                other => return other,
            }
        }
    }
}

/// A non-blocking socket read and written by waiting for it.
struct Polling(TcpStream);

impl Read for Polling {
    fn read(&mut self, buffer: &mut [u8]) -> io::Result<usize> {
        match self.0.read(buffer) {
            // The caller's patience is `Patient`'s: a wait that found nothing is a timeout it can count.
            Err(error) if error.kind() == io::ErrorKind::WouldBlock => {
                thread::sleep(Duration::from_millis(1));
                Err(io::ErrorKind::TimedOut.into())
            }
            other => other,
        }
    }
}

impl Write for Polling {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        loop {
            match self.0.write(bytes) {
                Err(error) if error.kind() == io::ErrorKind::WouldBlock => {
                    thread::sleep(Duration::from_millis(1));
                }
                other => return other,
            }
        }
    }

    fn flush(&mut self) -> io::Result<()> {
        self.0.flush()
    }
}

/// How a connection says it is done sending.
enum End {
    /// A TCP half-close.
    Shutdown(TcpStream),
    /// Dropping the writing half: a child's standard input.
    Writer,
    /// Everything at once: a Windows named pipe has no half-close, and a Unix socket here is treated alike.
    Everything,
}

/// One connection: its halves are used by two threads at once.
struct Conn {
    reader: Patient,
    writer: Box<dyn Write + Send>,
    end: End,
}

impl Conn {
    fn tcp(stream: TcpStream) -> Self {
        // Not a socket timeout: Windows leaves a socket whose receive timed out in an undefined state, and a loaded machine
        // is where one fires. Both halves poll a non-blocking socket instead.
        stream.set_nonblocking(true).expect("non-blocking");
        let writer = stream.try_clone().expect("a clone");
        Self {
            end: End::Shutdown(stream.try_clone().expect("a clone")),
            reader: Patient(Box::new(Polling(stream))),
            writer: Box::new(Polling(writer)),
        }
    }

    fn ipc(stream: PipeStream) -> Self {
        let halves = stream.split().expect("halves");
        Self {
            reader: Patient(Box::new(halves.reader)),
            writer: Box::new(halves.writer),
            end: End::Everything,
        }
    }

    /// Sends `send`'s bytes and reads `recv`'s, both ways at once, and checks what arrived.
    fn exchange(&mut self, send: u64, recv: u64) -> Result<(), String> {
        self.exchange_len(send, recv, LEN)
    }

    /// As [`Conn::exchange`], with `len` bytes each way.
    fn exchange_len(&mut self, send: u64, recv: u64, len: usize) -> Result<(), String> {
        let expected = digest_of(recv, len);
        let writer = &mut self.writer;
        let reader = &mut self.reader;
        thread::scope(|scope| {
            let writing = scope.spawn(|| {
                generate(send, len, |bytes| writer.write_all(bytes))
                    .and_then(|()| writer.flush())
                    .map_err(|error| format!("writing: {error}"))
            });
            let mut hasher = Sha256::new();
            let mut got = 0;
            let mut buffer = vec![0_u8; 16 * 1024];
            let read = (|| {
                while got < len {
                    let want = buffer.len().min(len - got);
                    match reader.read(&mut buffer[..want]) {
                        Ok(0) => return Err(format!("the end came after {got} of {len} bytes")),
                        Ok(count) => {
                            hasher.update(&buffer[..count]);
                            got += count;
                        }
                        Err(error) => return Err(format!("reading after {got} bytes: {error}")),
                    }
                }
                Ok(())
            })();
            let wrote = writing
                .join()
                .unwrap_or_else(|_| Err("the writer panicked".to_owned()));
            read?;
            wrote?;
            if hasher.finalize().to_vec() == expected {
                Ok(())
            } else {
                Err("the bytes that arrived are not the bytes that were sent".to_owned())
            }
        })
    }

    /// Says this side sends no more, and goes on reading.
    fn send_end(&mut self) {
        match &self.end {
            End::Shutdown(stream) => {
                let _ = stream.shutdown(std::net::Shutdown::Write);
            }
            End::Writer => self.writer = Box::new(io::sink()),
            End::Everything => {
                self.writer = Box::new(io::sink());
                self.reader = Patient(Box::new(io::empty()));
            }
        }
    }

    /// Sends the end and waits for the other side's, which has to arrive in order.
    fn close_in_order(&mut self) -> Result<(), String> {
        self.send_end();
        self.expect_end()
    }

    /// Reads until the end, which has to arrive in order: no more bytes and no error.
    fn expect_end(&mut self) -> Result<(), String> {
        let mut buffer = [0_u8; 64];
        match self.reader.read(&mut buffer) {
            Ok(0) => Ok(()),
            Ok(count) => Err(format!("{count} bytes came where the end was due")),
            Err(error) => Err(format!("the end was not in order: {error}")),
        }
    }
}

/// Which side closes first after the bytes have crossed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Closer {
    /// The end that holds the target (or the process that was started to be the target).
    Target,
    /// The end that opened the connection.
    Client,
}

const CLOSERS: [Closer; 2] = [Closer::Target, Closer::Client];

// Endpoints of any kind.

/// The kinds a case pairs. `Ipc` is a Unix socket on Unix and a named pipe on Windows.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    Tcp,
    Ipc,
}

static COUNTER: AtomicUsize = AtomicUsize::new(0);

/// A name for a socket or pipe of this test, as the text a target or a bind is written in (`unix:PATH`, `pipe:NAME`).
fn ipc_text(dir: &Path, tag: &str) -> String {
    let n = COUNTER.fetch_add(1, Ordering::SeqCst);
    if cfg!(windows) {
        format!("pipe:bohio-m-{}-{n}-{tag}", std::process::id())
    } else {
        format!("unix:{}", dir.join(format!("{tag}{n}.sock")).display())
    }
}

/// The name a socket or pipe text stands for.
fn pipe_name(text: &str) -> PipeName {
    if let Some(path) = text.strip_prefix("unix:") {
        PipeName::at(path).expect("a socket name")
    } else {
        let name = text.strip_prefix("pipe:").expect("a pipe text");
        PipeName::at(format!(r"\\.\pipe\{name}")).expect("a pipe name")
    }
}

/// Connects to an address as the host prints it or a target is written.
fn connect_to(text: &str) -> Conn {
    if text.starts_with("unix:") || text.starts_with("pipe:") {
        let options = Options::default();
        let stream = bohio_client::forward::ipc::connect(&pipe_name(text), WAIT, &options)
            .unwrap_or_else(|error| panic!("{text}: {error}"));
        Conn::ipc(stream)
    } else {
        Conn::tcp(TcpStream::connect(text).unwrap_or_else(|error| panic!("{text}: {error}")))
    }
}

/// A server of `kind` that takes one connection, trades `seed_out`/`seed_in` bytes, then has `closer` close first.
struct Server {
    /// The text a target is written as.
    text: String,
    /// The `connect` or `listen` rule that covers it.
    rule: String,
    thread: JoinHandle<Result<(), String>>,
}

const SERVER_OUT: u64 = 11;
const CLIENT_OUT: u64 = 22;

fn serve(kind: Kind, dir: &Path, tag: &str, closer: Closer) -> Server {
    let (text, rule, accept): (String, String, Box<dyn FnOnce() -> Conn + Send>) = match kind {
        Kind::Tcp => {
            let listener = TcpListener::bind("127.0.0.1:0").expect("a port");
            let port = listener.local_addr().expect("an address").port();
            (
                format!("127.0.0.1:{port}"),
                format!("127.0.0.1:{port}"),
                Box::new(move || Conn::tcp(listener.accept().expect("a connection").0)),
            )
        }
        Kind::Ipc => {
            let text = ipc_text(dir, tag);
            let listener = PipeListener::builder()
                .name(pipe_name(&text))
                .build()
                .expect("it listens");
            (
                text.clone(),
                text,
                Box::new(move || Conn::ipc(listener.accept().expect("a connection"))),
            )
        }
    };
    let thread = thread::spawn(move || {
        let mut conn = accept();
        conn.exchange(SERVER_OUT, CLIENT_OUT)?;
        // Each side ends its own direction and then reads the other's end, so what closes last has nothing left to reset.
        match closer {
            Closer::Target => conn.close_in_order(),
            Closer::Client => {
                let seen = conn.expect_end();
                conn.send_end();
                seen
            }
        }
    });
    Server { text, rule, thread }
}

impl Server {
    fn finished(self) -> Result<(), String> {
        self.thread
            .join()
            .unwrap_or_else(|_| Err("the server panicked".to_owned()))
    }
}

// A child process with its streams.

/// A `bohio` child whose standard input and output carry the connection, and whose standard error is read for lines.
struct Stdio2 {
    child: Child,
    stderr: Arc<Mutex<Vec<u8>>>,
}

impl Stdio2 {
    fn start(mut command: Command) -> (Self, Conn) {
        let mut child = command
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .expect("bohio starts");
        let stdout = child.stdout.take().expect("stdout");
        let stdin = child.stdin.take().expect("stdin");
        let mut stderr = child.stderr.take().expect("stderr");
        let collected = Arc::new(Mutex::new(Vec::new()));
        let shared = Arc::clone(&collected);
        thread::spawn(move || {
            let mut buffer = [0_u8; 1024];
            while let Ok(count) = stderr.read(&mut buffer) {
                if count == 0 {
                    break;
                }
                shared.lock().unwrap().extend_from_slice(&buffer[..count]);
            }
        });
        (
            Self {
                child,
                stderr: collected,
            },
            Conn {
                reader: Patient(Box::new(stdout)),
                writer: Box::new(stdin),
                end: End::Writer,
            },
        )
    }

    fn stderr(&self) -> String {
        String::from_utf8_lossy(&self.stderr.lock().unwrap()).into_owned()
    }

    /// The first standard-error line that starts with `prefix`.
    fn line(&self, prefix: &str) -> String {
        let until = Instant::now() + WAIT;
        loop {
            let text = self.stderr();
            if let Some(rest) = text.lines().find_map(|line| line.strip_prefix(prefix)) {
                return rest.trim().to_owned();
            }
            assert!(Instant::now() < until, "no `{prefix}` line: {text}");
            thread::sleep(Duration::from_millis(20));
        }
    }

    /// The exit status, once it ends.
    fn status(&mut self) -> Option<i32> {
        let until = Instant::now() + WAIT;
        loop {
            if let Some(status) = self.child.try_wait().expect("the child can be asked") {
                return status.code();
            }
            assert!(
                Instant::now() < until,
                "bohio did not end: {}",
                self.stderr()
            );
            thread::sleep(Duration::from_millis(20));
        }
    }
}

impl Drop for Stdio2 {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}

// What the node grants a command-line peer.

fn connect_grant(rules: &[&str]) -> Grant {
    Grant::allowing([Permission::ForwardConnect]).with_connect(rules.iter().copied())
}

fn listen_grant(rules: &[&str]) -> Grant {
    Grant::allowing([Permission::ForwardListen]).with_listen(rules.iter().copied())
}

/// A node and a command-line peer holding `grant`: the node, the peer's configuration path and the node's id.
fn node_and_peer(dir: &Path, grant: Grant) -> (Running, String, String) {
    let node = Running::start();
    let config = client_config(dir, "peer");
    let peer = id_of(&config);
    node.keys.accept(peer);
    node.grants.set(peer, grant);
    let server = node.id.to_string();
    (node, config.to_string_lossy().into_owned(), server)
}

fn expect_ok(label: &str, results: &[Result<(), String>]) {
    let failed: Vec<_> = results.iter().filter_map(|r| r.as_ref().err()).collect();
    assert!(failed.is_empty(), "{label}: {failed:?}");
}

// The matrix.

/// `-L`: a local listener of kind `local`, the host connecting to a target of kind `remote`.
fn dash_l(local: Kind, remote: Kind, closer: Closer) {
    let dir = tempfile::tempdir().expect("a directory");
    let target = serve(remote, dir.path(), "target", closer);
    let (node, config, server) = node_and_peer(dir.path(), connect_grant(&[target.rule.as_str()]));
    let listener = match local {
        Kind::Tcp => "127.0.0.1:0".to_owned(),
        Kind::Ipc => ipc_text(dir.path(), "local"),
    };
    let spec = format!("{listener}={}", target.text);
    let mut args = remote_args(&node, &config, &server);
    args.extend(["forward", "-L", spec.as_str()]);
    let forward = Spawned::start(bohio(&args));
    let line = forward.line("local ");
    let (bound, shown) = line.split_once(" -> ").expect("local BOUND -> TARGET");
    assert_eq!(shown, target.text);
    let bound = if local == Kind::Ipc {
        // The listener prints the name it bound, in the form the transport uses; the test knows it as written.
        listener
    } else {
        bound.to_owned()
    };
    let mut client = connect_to(&bound);
    let exchanged = client.exchange(CLIENT_OUT, SERVER_OUT);
    let ended = end_as_client(&mut client, closer);
    expect_ok(
        &format!(
            "-L {local:?} to {remote:?}, {closer:?} closes: {}",
            forward.stderr()
        ),
        &[exchanged, ended, target.finished()],
    );
}

/// `-R`: the host listens as `remote`, each arrival goes to a local target of kind `local`.
fn dash_r(remote: Kind, local: Kind, closer: Closer) {
    let dir = tempfile::tempdir().expect("a directory");
    let target = serve(local, dir.path(), "target", closer);
    let bind = match remote {
        Kind::Tcp => "127.0.0.1:0".to_owned(),
        Kind::Ipc => ipc_text(dir.path(), "remote"),
    };
    let (node, config, server) = node_and_peer(dir.path(), listen_grant(&[bind.as_str()]));
    let spec = format!("{bind}={}", target.text);
    let mut args = remote_args(&node, &config, &server);
    args.extend(["forward", "-R", spec.as_str()]);
    let forward = Spawned::start(bohio(&args));
    let line = forward.line("remote ");
    let (address, shown) = line.split_once(" -> ").expect("remote ADDRESS -> LOCAL");
    assert_eq!(shown, target.text);
    // The process that connects to the host's listener is the host's own.
    let mut client = connect_to(address);
    let exchanged = client.exchange(CLIENT_OUT, SERVER_OUT);
    let ended = end_as_client(&mut client, closer);
    expect_ok(
        &format!(
            "-R {remote:?} to {local:?}, {closer:?} closes: {}",
            forward.stderr()
        ),
        &[exchanged, ended, target.finished()],
    );
}

/// `connect`: standard input and output to a target of kind `remote`.
fn connect_stdio(remote: Kind, closer: Closer) {
    let dir = tempfile::tempdir().expect("a directory");
    let target = serve(remote, dir.path(), "target", closer);
    let (node, config, server) = node_and_peer(dir.path(), connect_grant(&[target.rule.as_str()]));
    let mut args = remote_args(&node, &config, &server);
    args.extend(["connect", target.text.as_str()]);
    let (mut child, mut conn) = Stdio2::start(bohio(&args));
    let exchanged = conn.exchange(CLIENT_OUT, SERVER_OUT);
    let ended = end_as_client(&mut conn, closer);
    let status = child.status();
    expect_ok(
        &format!(
            "connect to {remote:?}, {closer:?} closes: {}",
            child.stderr()
        ),
        &[exchanged, ended, target.finished()],
    );
    assert_eq!(
        status,
        Some(0),
        "an end in order is status 0: {}",
        child.stderr()
    );
}

/// `listen`: the host listens as `remote`, one arrival meets standard input and output.
fn listen_stdio(remote: Kind, closer: Closer) {
    let dir = tempfile::tempdir().expect("a directory");
    let bind = match remote {
        Kind::Tcp => "127.0.0.1:0".to_owned(),
        Kind::Ipc => ipc_text(dir.path(), "remote"),
    };
    let (node, config, server) = node_and_peer(dir.path(), listen_grant(&[bind.as_str()]));
    let mut args = remote_args(&node, &config, &server);
    args.extend(["listen", bind.as_str()]);
    let (mut child, mut conn) = Stdio2::start(bohio(&args));
    let address = child.line("listening ");
    let mut host_side = connect_to(&address);
    let (exchanged, host_exchanged) = thread::scope(|scope| {
        let host = scope.spawn(|| host_side.exchange(SERVER_OUT, CLIENT_OUT));
        let mine = conn.exchange(CLIENT_OUT, SERVER_OUT);
        (
            mine,
            host.join().unwrap_or_else(|_| Err("panicked".to_owned())),
        )
    });
    // `Target` is the host side's process here: it ends first, and the standard streams read the end.
    let ended = match closer {
        Closer::Target => {
            host_side.send_end();
            let seen = conn.expect_end();
            conn.send_end();
            let echoed = host_side.expect_end();
            seen.and(echoed)
        }
        Closer::Client => {
            conn.send_end();
            let seen = host_side.expect_end();
            host_side.send_end();
            let echoed = conn.expect_end();
            seen.and(echoed)
        }
    };
    let status = child.status();
    expect_ok(
        &format!("listen {remote:?}, {closer:?} closes: {}", child.stderr()),
        &[exchanged, host_exchanged, ended],
    );
    assert_eq!(
        status,
        Some(0),
        "an end in order is status 0: {}",
        child.stderr()
    );
}

/// The end of a case from the side that opened the connection: it ends first or reads the target's end first, and then
/// answers it, so each side ends its own direction and reads the other's.
fn end_as_client(client: &mut Conn, closer: Closer) -> Result<(), String> {
    match closer {
        Closer::Target => {
            let seen = client.expect_end();
            client.send_end();
            seen
        }
        Closer::Client => client.close_in_order(),
    }
}

macro_rules! matrix {
    ($($name:ident: $function:ident($first:expr, $second:expr);)*) => {$(
        #[test]
        fn $name() {
            let _deadline = Deadline::start();
            for closer in CLOSERS {
                $function($first, $second, closer);
            }
        }
    )*};
}

macro_rules! single {
    ($($name:ident: $function:ident($kind:expr);)*) => {$(
        #[test]
        fn $name() {
            let _deadline = Deadline::start();
            for closer in CLOSERS {
                $function($kind, closer);
            }
        }
    )*};
}

