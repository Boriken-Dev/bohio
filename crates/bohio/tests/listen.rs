//! Remote forwards: `bohio-listen/1` and `bohio-accept/1` against an embedded node, and `bohio remote ... forward -R`, `listen`,
//! `connect` and `forward -L` through the built binary.
//!
//! The matrix pairs every kind of endpoint on one side with every kind on the other, in each direction: `-L` (a local
//! listener of this machine's kind, the host connects to a target kind), `-R` (the host listens, each arrival goes to a local
//! target kind), `connect` (standard input and output to a target kind) and `listen` (a listener kind to standard input and
//! output). TCP and the machine's own local kind (a Unix socket, or a Windows named pipe) are the kinds here; a Unix socket on
//! one peer and a named pipe on the other need two operating systems and are the cross-site run's.
//!
//! Each case sends several MiB of generated bytes both ways at once and checks a SHA-256 of what arrived, then has one side
//! close and the other read the end in order.

