// Many forwards at once.

/// Bytes each way in a stress forward: sixteen run together, and a debug build on a slow disk moves them in a few seconds.
const STRESS_LEN: usize = 1024 * 1024;

/// One TCP forward through a local listener of this process: `how` varies who ends first and whether a side reads slowly.
#[derive(Debug, Clone, Copy)]
enum Ending {
    /// The target sends everything and closes at once, without reading to the client's end.
    TargetCloses,
    /// The client sends everything and half-closes at once; the target replies after the end.
    ClientHalfCloses,
    /// As `TargetCloses`, and the client reads slowly.
    SlowClient,
    /// The client has everything and drops its socket at once, with nothing sent to say so; the target waits for the end.
    ClientDrops,
}

fn one_forward(link: &dyn Open, ending: Ending, index: u64) -> Result<(), String> {
    use bohio_client::forward::{ForwardSettings, listen_tcp};
    use std::sync::atomic::AtomicBool;
    let target = TcpListener::bind("127.0.0.1:0").map_err(|e| e.to_string())?;
    let port = target.local_addr().map_err(|e| e.to_string())?.port();
    let local = TcpListener::bind("127.0.0.1:0").map_err(|e| e.to_string())?;
    let local_address = local.local_addr().map_err(|e| e.to_string())?;
    let stop = AtomicBool::new(false);
    let settings = ForwardSettings::default();
    let goal = Target::Tcp {
        host: "127.0.0.1".to_owned(),
        port,
    };
    let (seed_server, seed_client) = (100 + index, 200 + index);
    let refused = Mutex::new(Vec::new());
    let note = |error: &Error| refused.lock().unwrap().push(format!("{error:?}"));
    thread::scope(|scope| {
        let server = scope.spawn(|| -> Result<(), String> {
            target.set_nonblocking(true).map_err(|e| e.to_string())?;
            let until = Instant::now() + WAIT;
            let connection = loop {
                match target.accept() {
                    Ok((connection, _)) => break connection,
                    Err(e) if e.kind() == io::ErrorKind::WouldBlock && Instant::now() < until => {
                        thread::sleep(Duration::from_millis(5));
                    }
                    Err(e) => return Err(format!("the target was never reached: {e}")),
                }
            };
            connection
                .set_nonblocking(true)
                .map_err(|e| e.to_string())?;
            let mut conn = Conn::tcp(connection);
            match ending {
                Ending::ClientHalfCloses => {
                    // Reads to the client's end first, then answers.
                    let expected = digest_of(seed_client, STRESS_LEN);
                    let mut hasher = Sha256::new();
                    let mut buffer = vec![0_u8; 16 * 1024];
                    loop {
                        match conn.reader.read(&mut buffer) {
                            Ok(0) => break,
                            Ok(n) => hasher.update(&buffer[..n]),
                            Err(e) => return Err(format!("server read: {e}")),
                        }
                    }
                    if hasher.finalize().to_vec() != expected {
                        return Err("the client's bytes arrived changed".to_owned());
                    }
                    generate(seed_server, STRESS_LEN, |b| conn.writer.write_all(b))
                        .map_err(|e| format!("server write: {e}"))?;
                    conn.send_end();
                    Ok(())
                }
                Ending::TargetCloses | Ending::SlowClient => {
                    // Sends at the same time as it reads, then closes at once: nothing is left unread.
                    conn.exchange_len(seed_server, seed_client, STRESS_LEN)?;
                    drop(conn);
                    Ok(())
                }
                Ending::ClientDrops => {
                    conn.exchange_len(seed_server, seed_client, STRESS_LEN)?;
                    conn.expect_end()
                }
            }
        });
        let client = scope.spawn(|| -> Result<(), String> {
            let connection = TcpStream::connect(local_address).map_err(|e| e.to_string())?;
            connection
                .set_nonblocking(true)
                .map_err(|e| e.to_string())?;
            let mut conn = Conn::tcp(connection);
            match ending {
                Ending::ClientHalfCloses => {
                    generate(seed_client, STRESS_LEN, |b| conn.writer.write_all(b))
                        .map_err(|e| format!("client write: {e}"))?;
                    conn.send_end();
                    let expected = digest_of(seed_server, STRESS_LEN);
                    let mut hasher = Sha256::new();
                    let mut buffer = vec![0_u8; 16 * 1024];
                    loop {
                        match conn.reader.read(&mut buffer) {
                            Ok(0) => break,
                            Ok(n) => hasher.update(&buffer[..n]),
                            Err(e) => return Err(format!("client read: {e}")),
                        }
                    }
                    if hasher.finalize().to_vec() == expected {
                        Ok(())
                    } else {
                        Err("the target's bytes arrived changed".to_owned())
                    }
                }
                Ending::ClientDrops => {
                    conn.exchange_len(seed_client, seed_server, STRESS_LEN)?;
                    drop(conn);
                    Ok(())
                }
                Ending::TargetCloses | Ending::SlowClient => {
                    if matches!(ending, Ending::SlowClient) {
                        thread::sleep(Duration::from_millis(300));
                    }
                    conn.exchange_len(seed_client, seed_server, STRESS_LEN)?;
                    conn.expect_end()
                }
            }
        });
        let listening = scope.spawn(|| listen_tcp(link, &local, &goal, &settings, &stop, &note));
        let results = [
            server
                .join()
                .unwrap_or_else(|_| Err("server panicked".to_owned())),
            client
                .join()
                .unwrap_or_else(|_| Err("client panicked".to_owned())),
        ];
        stop.store(true, Ordering::SeqCst);
        let _ = listening.join();
        let refusals = refused.lock().unwrap().join("; ");
        results
            .into_iter()
            .collect::<Result<Vec<_>, _>>()
            .map(|_| ())
            .map_err(|error| format!("{error} (refused: {refusals})"))
    })
}

#[test]
fn many_tcp_forwards_on_one_link_end_in_order_whoever_closes_first() {
    let _deadline = Deadline::start();
    // Sixteen connections open their streams at the same moment: the host's bound on opens not yet taken up is a refusal
    // of the ones past it, and a slow machine has more of them waiting.
    let node = Running::with_link(
        ForwardConfig {
            max_connections_per_peer: 64,
            ..ForwardConfig::default()
        },
        LinkConfig {
            max_pending_opens: 64,
            ..LinkConfig::default()
        },
    );
    let rules = ["127.0.0.1:*"];
    let (link, _) = node.link(connect_grant(&rules));
    let endings = [
        Ending::TargetCloses,
        Ending::ClientHalfCloses,
        Ending::SlowClient,
        Ending::ClientDrops,
    ];
    let failures: Vec<String> = thread::scope(|scope| {
        let handles: Vec<_> = (0..16_u64)
            .map(|index| {
                let link = &link;
                scope.spawn(move || {
                    let ending = endings[usize::try_from(index).unwrap() % endings.len()];
                    one_forward(link, ending, index)
                        .map_err(|e| format!("#{index} {ending:?}: {e}"))
                })
            })
            .collect();
        handles
            .into_iter()
            .filter_map(|h| {
                h.join()
                    .unwrap_or_else(|_| Err("panicked".to_owned()))
                    .err()
            })
            .collect()
    });
    assert!(failures.is_empty(), "{failures:#?}");
}
