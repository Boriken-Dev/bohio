#[test]
fn a_revoke_ends_the_listener_and_its_connections_within_two_rechecks() {
    let _deadline = Deadline::start();
    for kind in [Kind::Tcp, Kind::Ipc] {
        let dir = tempfile::tempdir().expect("a directory");
        let node = Running::start();
        let bind_text = match kind {
            Kind::Tcp => "127.0.0.1:0".to_owned(),
            Kind::Ipc => ipc_text(dir.path(), "revoke"),
        };
        let (link, peer) = node.link(listen_grant(&[bind_text.as_str()]));
        let settings = ForwardSettings::default();
        let bind: Bind = bind_text.parse().expect("a bind");
        let listener = listen(&link, &bind, None, &settings).expect("listening");
        let address = listener.address().to_owned();
        let mut client = connect_to(&address);
        let arrival = listener
            .next_arrival(Some(WAIT))
            .expect("an arrival")
            .expect("not a timeout");
        let tunnel = listener
            .accept(&link, &arrival, &settings)
            .expect("claimed");
        tunnel.stream().send(b"live").expect("sent");
        let mut live = [0_u8; 4];
        client
            .reader
            .read_exact(&mut live)
            .expect("a live connection");
        assert_eq!(&live, b"live");

        node.grants.remove(&peer);
        let started = Instant::now();
        // The claimed connection ends with a revoke.
        let failure = loop {
            match tunnel.stream().receive(Some(Duration::from_millis(100))) {
                Err(Failure::Timeout) | Ok(Some(_)) => {}
                Err(failure) => break failure,
                Ok(None) => panic!("{kind:?}: the stream ended in order, not as a revoke"),
            }
            assert!(
                started.elapsed() < WAIT,
                "{kind:?}: the connection was not ended"
            );
        };
        assert_eq!(failure, Failure::Permission, "{kind:?}");
        assert!(
            started.elapsed() <= RECHECK * 2 + SLACK,
            "{kind:?}: took {:?}",
            started.elapsed()
        );
        // The host's end of it is reset, not finished.
        let mut rest = [0_u8; 8];
        let after = client.reader.read(&mut rest);
        assert!(
            !matches!(after, Ok(count) if count > 0),
            "{kind:?}: bytes came after a revoke"
        );
        // The listener is gone: nothing accepts there now.
        let until = Instant::now() + RECHECK * 2 + SLACK;
        loop {
            let gone = match kind {
                Kind::Tcp => TcpStream::connect(&address).is_err(),
                Kind::Ipc => bohio_client::forward::ipc::connect(
                    &pipe_name(&address),
                    Duration::from_millis(200),
                    &Options::default(),
                )
                .is_err(),
            };
            if gone {
                break;
            }
            assert!(
                Instant::now() < until,
                "{kind:?}: the listener still accepts"
            );
            thread::sleep(Duration::from_millis(50));
        }
        // The peer's listen stream ended with the revoke too.
        let ended = listener.next_arrival(Some(WAIT));
        assert!(ended.is_err(), "{kind:?}: {ended:?}");
        assert!(!listener.is_open());
    }
}

